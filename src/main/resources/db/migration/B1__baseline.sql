CREATE SEQUENCE product_location_seq START WITH 1 INCREMENT BY 50;

CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(255) NOT NULL,
    password VARCHAR(255) NOT NULL,
    role VARCHAR(255) NOT NULL,
    default_location VARCHAR(255),
    name VARCHAR(255),
    CONSTRAINT uk_users_username UNIQUE (username)
);

CREATE TABLE product (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT,
    name VARCHAR(255) NOT NULL,
    price DOUBLE PRECISION,
    CONSTRAINT uk_product_name UNIQUE (name)
);

CREATE TABLE product_location (
    id BIGINT PRIMARY KEY,
    user_id BIGINT,
    location_name VARCHAR(255),
    quantity INTEGER NOT NULL,
    product_id BIGINT,
    CONSTRAINT fk_product_location_product
        FOREIGN KEY (product_id) REFERENCES product (id)
);

CREATE TABLE location_names (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    location_name VARCHAR(255) NOT NULL,
    CONSTRAINT uk_location_names_user_location
        UNIQUE (user_id, location_name)
);

CREATE TABLE logbook (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT,
    action_type VARCHAR(255) NOT NULL,
    timestamp TIMESTAMP(6) NOT NULL,
    quantity INTEGER NOT NULL,
    amount DOUBLE PRECISION,
    notes VARCHAR(255),
    product_id BIGINT,
    product_location_id BIGINT,
    CONSTRAINT fk_logbook_product
        FOREIGN KEY (product_id) REFERENCES product (id),
    CONSTRAINT fk_logbook_product_location
        FOREIGN KEY (product_location_id) REFERENCES product_location (id)
);

CREATE TABLE customer (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    name VARCHAR(120) NOT NULL,
    phone VARCHAR(32),
    created_at TIMESTAMP(6) NOT NULL,
    updated_at TIMESTAMP(6) NOT NULL
);

CREATE INDEX idx_customer_user_name ON customer (user_id, name);
CREATE INDEX idx_customer_user_phone ON customer (user_id, phone);

CREATE TABLE invoice (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_number VARCHAR(32) NOT NULL,
    user_id BIGINT NOT NULL,
    operation VARCHAR(16) NOT NULL,
    status VARCHAR(16) NOT NULL,
    created_at TIMESTAMP(6) NOT NULL,
    voided_at TIMESTAMP(6),
    customer_id BIGINT,
    assigned_at TIMESTAMP(6),
    total_amount DOUBLE PRECISION,
    currency VARCHAR(16) NOT NULL,
    item_count INTEGER NOT NULL,
    product_summary VARCHAR(255) NOT NULL,
    CONSTRAINT uk_invoice_number UNIQUE (invoice_number),
    CONSTRAINT ck_invoice_operation CHECK (operation IN ('ADD', 'SELL')),
    CONSTRAINT ck_invoice_status CHECK (status IN ('ACTIVE', 'VOIDED')),
    CONSTRAINT fk_invoice_customer
        FOREIGN KEY (customer_id) REFERENCES customer (id)
);

CREATE INDEX idx_invoice_customer_assignment
    ON invoice (customer_id, status, operation);

CREATE TABLE invoice_item (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_id BIGINT NOT NULL,
    product_id BIGINT,
    product_name VARCHAR(255),
    location_id BIGINT,
    location_name VARCHAR(255),
    quantity INTEGER NOT NULL,
    unit VARCHAR(255),
    unit_price DOUBLE PRECISION,
    discount DOUBLE PRECISION,
    subtotal DOUBLE PRECISION,
    stock_before INTEGER NOT NULL,
    stock_after INTEGER NOT NULL,
    CONSTRAINT fk_invoice_item_invoice
        FOREIGN KEY (invoice_id) REFERENCES invoice (id)
);
