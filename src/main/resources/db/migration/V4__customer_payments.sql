CREATE TABLE customer_payment_entry (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    customer_id BIGINT NOT NULL,
    entry_type VARCHAR(16) NOT NULL,
    amount NUMERIC(19,2) NOT NULL,
    currency VARCHAR(16) NOT NULL DEFAULT 'som',
    method VARCHAR(32),
    occurred_at TIMESTAMP(6) NOT NULL,
    created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    note VARCHAR(500),
    reversal_reason VARCHAR(500),
    reversal_of_payment_id BIGINT,
    idempotency_key VARCHAR(255) NOT NULL,
    request_fingerprint VARCHAR(64) NOT NULL,
    CONSTRAINT ck_customer_payment_entry_type
        CHECK (entry_type IN ('PAYMENT', 'REVERSAL')),
    CONSTRAINT ck_customer_payment_amount
        CHECK (amount > 0),
    CONSTRAINT ck_customer_payment_currency
        CHECK (currency = 'som'),
    CONSTRAINT ck_customer_payment_shape CHECK (
        (entry_type = 'PAYMENT'
            AND method IN ('CASH', 'CARD', 'BANK_TRANSFER', 'OTHER')
            AND reversal_of_payment_id IS NULL
            AND reversal_reason IS NULL)
        OR
        (entry_type = 'REVERSAL'
            AND method IS NULL
            AND reversal_of_payment_id IS NOT NULL
            AND reversal_reason IS NOT NULL)
    ),
    CONSTRAINT fk_customer_payment_customer
        FOREIGN KEY (customer_id) REFERENCES customer (id),
    CONSTRAINT fk_customer_payment_reversal
        FOREIGN KEY (reversal_of_payment_id) REFERENCES customer_payment_entry (id),
    CONSTRAINT uk_customer_payment_reversal
        UNIQUE (reversal_of_payment_id),
    CONSTRAINT uk_customer_payment_user_idempotency
        UNIQUE (user_id, idempotency_key)
);

CREATE INDEX idx_customer_payment_history
    ON customer_payment_entry (user_id, customer_id, occurred_at DESC, id DESC);

CREATE INDEX idx_customer_payment_balance
    ON customer_payment_entry (user_id, customer_id, entry_type)
    INCLUDE (amount);

CREATE FUNCTION prevent_customer_payment_entry_mutation()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    RAISE EXCEPTION 'customer payment entries are immutable';
END;
$$;

CREATE TRIGGER trg_customer_payment_entry_immutable
    BEFORE UPDATE OR DELETE ON customer_payment_entry
    FOR EACH ROW
    EXECUTE FUNCTION prevent_customer_payment_entry_mutation();

ALTER TABLE logbook
    ADD COLUMN customer_id BIGINT,
    ADD COLUMN customer_name VARCHAR(120),
    ADD COLUMN payment_entry_id BIGINT,
    ADD COLUMN currency VARCHAR(16),
    ADD CONSTRAINT fk_logbook_customer
        FOREIGN KEY (customer_id) REFERENCES customer (id),
    ADD CONSTRAINT fk_logbook_payment_entry
        FOREIGN KEY (payment_entry_id) REFERENCES customer_payment_entry (id);

CREATE INDEX idx_logbook_user_customer_timestamp_id
    ON logbook (user_id, customer_id, timestamp DESC, id DESC)
    WHERE customer_id IS NOT NULL;
